const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const {buildTutorInput,buildOllamaMessages,validateAttachment}=require("./server");
const core=vm.runInNewContext(fs.readFileSync("study-core.js","utf8")+";StudySprintCore");
const now=new Date("2026-11-12T12:00:00");
assert.equal(core.daysUntil("2026-11-13",now),1);
assert(core.priority({confidence:1,minutes:60},"2026-11-13",now)>core.priority({confidence:5,minutes:30},"2026-11-20",now));
const subjects=[{id:"a",name:"Math",topics:[{id:"t1",name:"Algebra",confidence:1,minutes:60},{id:"t2",name:"Stats",confidence:5,minutes:30}]}];
const exams=[{id:"e",subjectId:"a",name:"Math exam",date:"2026-11-20"}];
const plan=core.makePlan(subjects,exams,60,now);
assert(plan.length>0);assert.equal(plan[0].date,"2026-11-12");assert.equal(plan[0].minutes,60);assert.equal(plan[0].topic,"Algebra");
const smallPlan=core.makePlan(subjects,exams,20,now);
assert(smallPlan.length>0);
assert(smallPlan.every(x=>x.minutes>0&&x.minutes<=20));
assert.equal(smallPlan.reduce((sum,x)=>sum+x.minutes,0),90);
assert.throws(()=>validateAttachment({data:"not-a-data-url"}),/Unsupported attachment/);
assert.throws(()=>validateAttachment({data:"data:text/plain;base64,SGk="}),/accepts images and PDFs/);
const pdf=Buffer.from("%PDF-1.4 test").toString("base64");
const built=buildTutorInput({message:"Explain this",mode:"Explain simply",attachment:{name:"notes.pdf",type:"application/pdf",data:"data:application/pdf;base64,"+pdf},history:[{role:"user",text:"previous"}],context:{subjects:[{name:"Math",topics:[{name:"Algebra",confidence:2}]}],exams:[],currentTask:null}});
assert.equal(built.input.at(-1).content[1].type,"input_file");assert.equal(built.input.at(-1).content[1].filename,"notes.pdf");assert.equal(built.input.length,3);
const ollama=buildOllamaMessages({message:"What is algebra?",mode:"Explain simply",context:{subjects:[],exams:[],currentTask:null}});
assert.equal(ollama.at(-1).role,"user");assert.match(ollama.at(-1).content,/What is algebra/);
console.log("StudySprint tests: PASS");
